import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, copyFileSync, writeFileSync, readdirSync, statSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Where the ESP-01S sketch lives inside the plugin. */
export const SKETCH_DIR = join(HERE, '..', 'firmware', 'esp01s')
/** Per-user firmware output (gitignored: it can contain baked credentials). */
export const BUILD_DIR = join(SKETCH_DIR, 'build')
/** ESP-01S: 1 MB flash, 80 MHz (kept for the old modules). */
export const FQBN = 'esp8266:esp8266:generic:eesz=1M,xtal=80'
/** ESP-12E / NodeMCU: 4 MB, own USB and 3.3 V regulator - the recommended carrier. */
export const FQBN_NODEMCU = 'esp8266:esp8266:nodemcuv2'
export const BOARDS = {
  nodemcu: { label: 'ESP-12E / NodeMCU', fqbn: FQBN_NODEMCU, boardDefine: '' },
  esp01s: { label: 'ESP-01S', fqbn: FQBN, boardDefine: '-DBOARD_NODEMCU=0' },
}

/** The Arduino IDE ships its own arduino-cli; a PATH install also works. */
const CLI_CANDIDATES = [
  'D:\\Arduino\\Arduino IDE\\resources\\app\\lib\\backend\\resources\\arduino-cli.exe',
  'C:\\Program Files\\Arduino IDE\\resources\\app\\lib\\backend\\resources\\arduino-cli.exe',
  join(process.env.LOCALAPPDATA || '', 'Programs', 'Arduino IDE', 'resources', 'app', 'lib', 'backend', 'resources', 'arduino-cli.exe'),
]

/** Locate arduino-cli: explicit path, then the known IDE bundle, then PATH. */
export function findArduinoCli(preferred = '') {
  if (preferred && existsSync(preferred)) return preferred
  for (const candidate of CLI_CANDIDATES) if (candidate && existsSync(candidate)) return candidate
  return 'arduino-cli'
}

/** Arduino data dir: the IDE and the CLI share %LOCALAPPDATA%\Arduino15 on Windows. */
export function arduinoDataDir() {
  if (process.env.ARDUINO_DIRECTORIES_DATA) return process.env.ARDUINO_DIRECTORIES_DATA
  const local = process.env.LOCALAPPDATA || ''
  return local ? join(local, 'Arduino15') : ''
}

/** Installed ESP8266 platform version, or '' when the core is missing. */
export function findEsp8266Core() {
  const data = arduinoDataDir()
  if (!data) return ''
  const hardware = join(data, 'packages', 'esp8266', 'hardware', 'esp8266')
  if (!existsSync(hardware)) return ''
  const versions = readdirSync(hardware).filter((name) => existsSync(join(hardware, name, 'platform.txt')))
  return versions.length ? join(hardware, versions.sort().pop()) : ''
}

/** Everything the panel needs to know before offering the "generate" button. */
export function firmwareToolchain(preferredCli = '') {
  const cli = findArduinoCli(preferredCli)
  const core = findEsp8266Core()
  const cliPath = cli === 'arduino-cli' ? '' : cli
  return {
    ok: Boolean(core) && Boolean(cliPath || whichOnPath('arduino-cli')),
    cli: cliPath || 'arduino-cli',
    core: core ? core.split(/[\\/]/).slice(-1)[0] : '',
    corePath: core,
    data: arduinoDataDir(),
    fqbn: FQBN,
    sketch: SKETCH_DIR,
    build: BUILD_DIR,
  }
}

function whichOnPath(name) {
  const pathEnv = process.env.PATH || process.env.Path || ''
  for (const dir of pathEnv.split(';')) {
    const candidate = join(dir, name + (process.platform === 'win32' ? '.exe' : ''))
    if (dir && existsSync(candidate)) return candidate
  }
  return ''
}

/** C string literal for a #define, with quotes and backslashes escaped. */
export function cString(value) {
  return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'
}

/** Baud rates the ESP pipe can use; a slower link is far more tolerant of loose wires. */
export const PIPE_BAUDS = [9600, 19200, 38400, 57600, 74880, 115200, 230400, 460800, 921600]

/** Link protocols between host and bridge. Only 'stream' exists so far; the firmware carries
 *  the selector so the other two can be implemented without re-signing the shape of this API. */
export const LINK_MODES = [
  { id: 'stream', label: '流式（主机驱动 AN3155）', define: 'LINK_MODE_STREAM', implemented: true },
  { id: 'block', label: '块级 ACK（ESP 缓存一块并重试）', define: 'LINK_MODE_BLOCK', implemented: true },
  { id: 'spool', label: '全量缓存（镜像存 ESP 后自烧）', define: 'LINK_MODE_SPOOL', implemented: false },
]
export const LINK_MODE_DEFAULT = 'stream'

export const PIPE_BAUD_DEFAULT = 115200

/** The header the sketch includes when the panel baked credentials in. */
export function credentialsHeader(ssid, pass, baud, linkMode) {
  const value = Number(baud) > 0 ? Number(baud) : PIPE_BAUD_DEFAULT
  const mode = LINK_MODES.find((entry) => entry.id === linkMode) || LINK_MODES[0]
  return [
    '/* generated by dsh-stm32-toolchain - do not commit (contains the Wi-Fi password) */',
    '#pragma once',
    '#define WIFI_SSID ' + cString(ssid),
    '#define WIFI_PASS ' + cString(pass),
    '#define PIPE_BAUD ' + value,
    '#define LINK_MODE ' + mode.define,
    '',
  ].join('\n')
}

function run(command, args, options = {}) {
  return new Promise((resolve) => {
    const started = Date.now()
    const child = spawn(command, args, { windowsHide: true, ...options })
    let out = ''
    let err = ''
    const timer = setTimeout(() => { try { child.kill() } catch { /* already gone */ } }, options.timeoutMs || 240000)
    child.stdout.on('data', (chunk) => { out += chunk })
    child.stderr.on('data', (chunk) => { err += chunk })
    child.on('error', (error) => {
      clearTimeout(timer)
      resolve({ ok: false, code: -1, out, err: String(error.message), elapsedMs: Date.now() - started })
    })
    child.on('close', (code) => {
      clearTimeout(timer)
      resolve({ ok: code === 0, code, out, err, elapsedMs: Date.now() - started })
    })
  })
}

/**
 * Bake SSID/password into a fresh .bin.
 *
 * The credentials are written as a header inside a temporary copy of the sketch - they
 * never travel through a command line, so a password with quotes, spaces or '&' is safe.
 */
export async function generateFirmware(options = {}) {
  const ssid = String(options.ssid || '').trim()
  const pass = String(options.pass || '')
  if (!ssid) return { ok: false, error: 'Wi-Fi 名称不能为空' }
  if (ssid.length > 32) return { ok: false, error: 'Wi-Fi 名称最多 32 个字符' }
  if (pass.length > 63) return { ok: false, error: 'Wi-Fi 密码最多 63 个字符' }
  if (!existsSync(join(SKETCH_DIR, 'esp01s.ino'))) return { ok: false, error: '固件源码缺失: ' + SKETCH_DIR }

  const toolchain = firmwareToolchain(options.cli)
  if (!toolchain.ok) {
    return { ok: false, error: '缺少 Arduino 工具链（arduino-cli 或 ESP8266 核心未安装）', toolchain }
  }

  const board = BOARDS[options.board] || BOARDS.nodemcu
  const fqbn = options.eesz ? board.fqbn.replace(/eesz=[^,]+,/, 'eesz=' + String(options.eesz) + ',') : board.fqbn
  const work = mkdtempSync(join(tmpdir(), 'dsh-esp01s-'))
  const sketch = join(work, 'esp01s')
  mkdirSync(sketch, { recursive: true })
  copyFileSync(join(SKETCH_DIR, 'esp01s.ino'), join(sketch, 'esp01s.ino'))
  writeFileSync(join(sketch, 'wifi_creds.h'), credentialsHeader(ssid, pass, options.baud, options.linkMode), 'utf8')
  const outDir = join(work, 'build')

  const args = ['compile', '--fqbn', fqbn, '--output-dir', outDir]
  if (board.boardDefine) args.push('--build-property', 'compiler.cpp.extra_flags=' + board.boardDefine)
  args.push(sketch)
  const result = await run(toolchain.cli, args, { timeoutMs: options.timeoutMs || 300000 })

  let bin = ''
  let bytes = 0
  if (result.ok) {
    const produced = join(outDir, 'esp01s.ino.bin')
    if (existsSync(produced)) {
      mkdirSync(BUILD_DIR, { recursive: true })
      const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
      bin = join(BUILD_DIR, 'esp01s-' + stamp + '.bin')
      copyFileSync(produced, bin)
      bytes = statSync(bin).size
    }
  }
  try { rmSync(work, { recursive: true, force: true }) } catch { /* temp cleanup is best effort */ }

  const log = (result.out + result.err).split(/\r?\n/).filter((line) => line.trim()).slice(-6).join('\n')
  if (!result.ok) return { ok: false, error: '编译失败（见日志）', log, elapsedMs: result.elapsedMs, toolchain }
  if (!bin) return { ok: false, error: '编译完成但没有生成 .bin', log, elapsedMs: result.elapsedMs }
  return { ok: true, bin, bytes, ssid, elapsedMs: result.elapsedMs, log, toolchain: { cli: toolchain.cli, core: toolchain.core } }
}

/** Bundled python + esptool shipped by the ESP8266 core (used for detection only). */
export function espTools() {
  const core = findEsp8266Core()
  const data = arduinoDataDir()
  if (!core || !data) return { python: '', esptool: '' }
  const esptool = join(core, 'tools', 'esptool', 'esptool.py')
  const pyserial = join(core, 'tools', 'pyserial')
  const pythonRoot = join(data, 'packages', 'esp8266', 'tools', 'python3')
  let python = ''
  if (existsSync(pythonRoot)) {
    const versions = readdirSync(pythonRoot).sort()
    for (const version of versions) {
      const candidate = join(pythonRoot, version, 'python.exe')
      if (existsSync(candidate)) { python = candidate; break }
    }
  }
  return {
    python,
    esptool: existsSync(esptool) ? esptool : '',
    /* the module ships pyserial but does not install it for its own python */
    env: existsSync(pyserial) ? { ...process.env, PYTHONPATH: pyserial } : { ...process.env },
  }
}

/**
 * Ask the module what it is before blaming the sketch: flash_id reports the real size
 * (a 512 KB ESP-01 built for 1M puts the EEPROM sector past the end of flash and the
 * sketch crashes at boot - the classic "flashed fine, never runs" case).
 */
export async function detectEsp(options = {}) {
  const port = String(options.port || '').trim()
  if (!port) return { ok: false, error: '需要 ESP 的串口（USB-TTL），例如 COM5' }
  const { python, esptool, env } = espTools()
  if (!python || !esptool) return { ok: false, error: '找不到 esptool（ESP8266 核心未安装）' }

  const result = await run(python, [esptool, '--port', port, '--baud', '115200', '--before', 'default_reset', 'flash_id'], { timeoutMs: options.timeoutMs || 60000, env })
  const text = (result.out || '') + (result.err || '')
  const size = /Detected flash size:\s*([0-9A-Za-z]+)/i.exec(text)?.[1] || ''
  const chip = /Chip (?:is|type is)\s+([^\r\n]+)/i.exec(text)?.[1]?.trim() || ''
  const mac = /MAC:\s*([0-9a-f:]{17})/i.exec(text)?.[1] || ''
  const fqbnFor = { '1MB': '1M', '512KB': '512K', '2MB': '2M', '4MB': '4M' }[size.toUpperCase()] || ''
  return {
    ok: result.ok,
    port,
    chip,
    mac,
    flashSize: size,
    suggestedFqbn: fqbnFor ? 'esp8266:esp8266:generic:eesz=' + fqbnFor + ',xtal=80' : '',
    log: text.split(/\r?\n/).filter((line) => line.trim()).slice(-12).join('\n'),
    error: result.ok ? undefined : '读不到模块：GPIO0 要接地进烧录模式，或串口被占用/接错',
  }
}

/** Write a generated .bin to the ESP-01S (GPIO0 grounded at power-up). */
export async function flashEsp(options = {}) {
  const port = String(options.port || '').trim()
  const bin = String(options.bin || '').trim()
  if (!port) return { ok: false, error: '需要串口（ESP 的 USB-TTL 口，例如 COM5）' }
  if (!bin || !existsSync(bin)) return { ok: false, error: '没有可烧的固件，先生成一次' }

  const toolchain = firmwareToolchain(options.cli)
  if (!toolchain.ok) return { ok: false, error: '缺少 Arduino 工具链', toolchain }

  /* arduino-cli upload wants a build directory holding the .bin plus its metadata. */
  const staged = mkdtempSync(join(tmpdir(), 'dsh-esp-flash-'))
  copyFileSync(bin, join(staged, 'esp01s.ino.bin'))
  const args = ['upload', '-p', port, '-b', toolchain.fqbn, '--input-dir', staged]
  if (options.verify !== false) args.push('--verify')
  const result = await run(toolchain.cli, args, { timeoutMs: options.timeoutMs || 180000 })
  try { rmSync(staged, { recursive: true, force: true }) } catch { /* best effort */ }

  const log = (result.out + result.err).split(/\r?\n/).filter((line) => line.trim()).slice(-8).join('\n')
  return { ok: result.ok, port, bin, bytes: statSync(bin).size, elapsedMs: result.elapsedMs, log,
    error: result.ok ? undefined : '烧录失败（GPIO0 是否在烧录时接地？）' }
}
